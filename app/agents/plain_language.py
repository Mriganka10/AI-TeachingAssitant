"""Plain-language checks and safe wording cleanup for generated lesson content.

Two layers keep the writing simple and natural:

1. `style_issues` finds problems worth one model rewrite (very long sentences, stock filler phrases,
   self-references to AI, wordy diagram labels). These issues are *soft*: they can trigger a
   repair request, but they never fail a job.
2. `polish` applies small, meaning-preserving substitutions to every learner-visible string
   (for example "utilize" -> "use", em dashes -> commas). Citations, URLs, IDs, formulas and
   source titles are never touched.
"""

from __future__ import annotations

import re
from typing import Any

# Fields whose exact wording must be preserved.
_PROTECTED_KEYS = {
    "id",
    "url",
    "year",
    "source_type",
    "source_refs",
    "sources",
    "apa_references",
    "papers",
    "studies",
    "answer",
    "objective_id",
    "difficulty",
    "bloom_level",
    "level",
    "type",
    "confidence",
    "core_formulas",
    # Research review: manuscript quotes, locations and enum values stay exactly as written.
    "location",
    "evidence",
    "claim",
    "decision",
    "criterion",
    "status",
    "support",
    "priority",
    "effort",
    "guideline",
}

_SELF_REFERENCE = re.compile(
    r"\b(?:as an ai\b|language model|ai[- ]generated|generated by (?:an )?ai|this ai\b|"
    r"i hope this helps|as requested\b|as you requested|happy to help)",
    re.IGNORECASE,
)

STOCK_PHRASES = (
    "delve",
    "dive into",
    "in today's",
    "it is important to note",
    "it's important to note",
    "it is worth noting",
    "crucial role",
    "pivotal role",
    "a testament to",
    "tapestry",
    "realm of",
    "landscape of",
    "furthermore",
    "moreover",
    "in conclusion",
    "unlock the",
    "harness the",
    "seamless",
    "game-changer",
    "navigate the complexities",
)

# Filler openers removed from the start of a sentence; the next word is re-capitalised.
_OPENERS = re.compile(
    r"(?:^|(?<=[.!?]\s))(?:it(?: is|'s) (?:important|worth|crucial|essential) "
    r"(?:to note|noting|to remember|to understand) that|in today's (?:fast-paced |modern |"
    r"digital |ever-changing )?world,?)\s+(\w)",
    re.IGNORECASE,
)

# (pattern, replacement) pairs that keep the meaning and grammar intact.
_SUBSTITUTIONS: tuple[tuple[re.Pattern[str], str], ...] = tuple(
    (re.compile(pattern, re.IGNORECASE), replacement)
    for pattern, replacement in (
        (r"\bdelves into\b", "looks at"),
        (r"\bdelving into\b", "looking at"),
        (r"\bdelve into\b", "look at"),
        (r"\butili[sz]ation\b", "use"),
        (r"\butili[sz]es\b", "uses"),
        (r"\butili[sz]ed\b", "used"),
        (r"\butili[sz]ing\b", "using"),
        (r"\butili[sz]e\b", "use"),
        (r"\bin order to\b", "to"),
        (r"\bplays? a (?:crucial|pivotal|vital) role in\b", "is key to"),
        (r"\ba testament to\b", "a sign of"),
        (r"(^|(?<=[.!?]\s))(?:furthermore|moreover|additionally),\s+", r"\1Also, "),
        (r"(^|(?<=[.!?]\s))in conclusion,\s+", r"\1In short, "),
    )
)

_URL = re.compile(r"https?://\S+")


def polish(value: Any, *, key: str | None = None) -> Any:
    """Return a copy of the content with safe plain-language substitutions applied."""
    if key in _PROTECTED_KEYS:
        return value
    if isinstance(value, dict):
        return {item_key: polish(item, key=item_key) for item_key, item in value.items()}
    if isinstance(value, list):
        return [polish(item, key=key) for item in value]
    if isinstance(value, str):
        return polish_text(value)
    return value


_ACADEMIC_SUBSTITUTIONS = _SUBSTITUTIONS[:-2]  # word swaps only; keeps formal connectives


def polish_academic(text: str) -> str:
    """Manuscript-safe cleanup: stock phrases and em dashes, but formal connectives are kept."""
    if not text:
        return text
    parts = _URL.split(text)
    urls = _URL.findall(text)
    cleaned = []
    for part in parts:
        part = re.sub(r"(?<=\d)\s*—\s*(?=\d)", "–", part)
        part = re.sub(r"\s*—\s*", ", ", part)
        part = _OPENERS.sub(lambda match: match.group(1).upper(), part)
        for pattern, replacement in _ACADEMIC_SUBSTITUTIONS:
            part = pattern.sub(replacement, part)
        part = re.sub(r",\s*([,.;:!?])", r"\1", part)
        cleaned.append(re.sub(r"[ \t]{2,}", " ", part))
    return "".join(piece for pair in zip(cleaned, [*urls, ""], strict=True) for piece in pair)


def polish_text(text: str) -> str:
    if not text:
        return text
    # Leave URLs exactly as they are; polish only the prose between them.
    parts = _URL.split(text)
    urls = _URL.findall(text)
    polished = [_polish_prose(part) for part in parts]
    value = "".join(
        piece for pair in zip(polished, [*urls, ""], strict=True) for piece in pair
    )
    return value.strip() if text == text.strip() else value


def _polish_prose(value: str) -> str:
    # Number ranges keep a dash; elsewhere an em dash becomes a comma.
    value = re.sub(r"(?<=\d)\s*—\s*(?=\d)", "–", value)
    value = re.sub(r"\s*—\s*", ", ", value)
    value = _OPENERS.sub(lambda match: match.group(1).upper(), value)
    for pattern, replacement in _SUBSTITUTIONS:
        value = pattern.sub(replacement, value)
    value = re.sub(r",\s*([,.;:!?])", r"\1", value)
    return re.sub(r"[ \t]{2,}", " ", value)


def _visible_strings(agent_type: str, result: dict) -> list[str]:
    """Learner- or audience-facing text, which is what the style rules are for."""
    values: list[str] = []

    def collect(value: Any, key: str | None = None) -> None:
        if key in _PROTECTED_KEYS:
            return
        if isinstance(value, dict):
            for item_key, item in value.items():
                collect(item, item_key)
        elif isinstance(value, list):
            for item in value:
                collect(item, key)
        elif isinstance(value, str) and value.strip():
            values.append(value)

    overview = result.get("overview") if isinstance(result.get("overview"), dict) else {}
    collect(overview.get("lesson_purpose"))
    for section in result.get("lecture_sections") or []:
        if not isinstance(section, dict):
            continue
        content = section.get("content") if isinstance(section.get("content"), dict) else {}
        for key in ("explanation", "key_points", "worked_example", "common_errors",
                    "concept_check", "diagram"):
            collect(content.get(key), key)
    collect(result.get("mcqs"))
    collect(result.get("discussion_questions"))
    case_study = result.get("case_study")
    if isinstance(case_study, dict):
        collect(case_study.get("scenario"))
        collect(case_study.get("questions"))
    return values


def _sentences(text: str) -> list[str]:
    return [part for part in re.split(r"(?<=[.!?])\s+", text.strip()) if part]


def _research_strings(result: dict) -> list[str]:
    values: list[str] = []

    def collect(value: Any, key: str | None = None) -> None:
        if key in _PROTECTED_KEYS or key in {"title", "apa_references"}:
            return
        if isinstance(value, dict):
            for item_key, item in value.items():
                collect(item, item_key)
        elif isinstance(value, list):
            for item in value:
                collect(item, key)
        elif isinstance(value, str) and value.strip():
            values.append(value)

    collect(result)
    return values


def research_style_issues(result: dict) -> list[str]:
    """Reviewer-voice checks: no AI self-reference and no stock phrases. Never fails a job."""
    joined = "\n".join(_research_strings(result))
    issues: list[str] = []
    if _SELF_REFERENCE.search(joined):
        issues.append(
            "Remove every reference to AI, a model, an assistant or the requester; write as the "
            "reviewer addressing the authors."
        )
    lowered = joined.casefold()
    found = sorted(
        phrase
        for phrase in STOCK_PHRASES
        if phrase in lowered and phrase not in {"furthermore", "moreover", "in conclusion"}
    )
    if found:
        issues.append(
            "Replace stock phrases with precise wording: " + ", ".join(f'"{p}"' for p in found) + "."
        )
    return issues


def style_issues(agent_type: str, result: dict) -> list[str]:
    """Return plain-language problems worth one rewrite. Never used to fail a job."""
    if agent_type == "research":
        return research_style_issues(result)
    texts = _visible_strings(agent_type, result)
    joined = "\n".join(texts)
    issues: list[str] = []

    if _SELF_REFERENCE.search(joined):
        issues.append(
            "Remove every reference to AI, a model, an assistant or the requester; write as "
            "the teacher speaking directly to learners."
        )

    sentence_lengths = [len(sentence.split()) for text in texts for sentence in _sentences(text)]
    limit = 30
    long_count = sum(length > limit for length in sentence_lengths)
    if long_count:
        issues.append(
            f"{long_count} sentence(s) are longer than {limit} words. Split them into short "
            "sentences with one idea each."
        )
    prose = [length for length in sentence_lengths if length >= 6]
    average_limit = 20
    if prose and sum(prose) / len(prose) > average_limit:
        issues.append(
            f"Average sentence length is {sum(prose) / len(prose):.0f} words. Aim for 8 to 18."
        )

    lowered = joined.casefold()
    found = sorted({phrase for phrase in STOCK_PHRASES if phrase in lowered})
    if found:
        issues.append(
            "Replace stock phrases with plain wording: " + ", ".join(f'"{p}"' for p in found) + "."
        )

    wordy = []
    for section in result.get("lecture_sections") or []:
        content = section.get("content") if isinstance(section, dict) else None
        diagram = content.get("diagram") if isinstance(content, dict) else None
        for node in (diagram or {}).get("nodes") or []:
            if isinstance(node, dict) and len(str(node.get("label", "")).split()) > 5:
                wordy.append(str(node.get("label")))
    if wordy:
        issues.append("Shorten diagram labels to 1 to 4 words: " + "; ".join(wordy[:4]) + ".")
    return issues
